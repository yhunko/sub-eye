/**
 * Vendors Fixel into `public/fonts/` and writes `src/styles/fonts.css`.
 *
 *     bun run --cwd apps/landing fonts
 *
 * The page makes no third-party requests at runtime — that is a Lighthouse
 * requirement and also the page's own argument — so the files are downloaded
 * once, from MacPaw's repository at a pinned commit, and committed. Fixel is
 * not on Google Fonts, so nothing hands out per-script files: `pyftsubset`
 * (fontTools + brotli, `pip install fonttools brotli`) cuts each face into the
 * same three unicode ranges Google uses, and a visitor on `/en/` never
 * downloads the Cyrillic file. Re-run only when a face or weight changes.
 */
import { mkdir, mkdtemp, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";

const ROOT = join(dirname(new URL(import.meta.url).pathname), "..");
const FONT_DIR = join(ROOT, "public", "fonts");
const CSS_OUT = join(ROOT, "src", "styles", "fonts.css");

const COMMIT = "514fd02ea7d70668ed3dd09fb2674ba6f70d61ee";
const RAW = `https://raw.githubusercontent.com/MacPaw/Fixel/${COMMIT}`;

const FACES = [
  { family: "Fixel Display", file: "FixelDisplay-SemiBold", weight: 600 },
  { family: "Fixel Text", file: "FixelText-Regular", weight: 400 },
  { family: "Fixel Text", file: "FixelText-Medium", weight: 500 },
];

// Google's ranges for its own latin / latin-ext / cyrillic files. The hryvnia
// (U+20B4) sits in latin-ext, which every locale loads.
const SUBSETS: Record<string, string> = {
  latin:
    "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD",
  "latin-ext":
    "U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF",
  cyrillic: "U+0301, U+0400-045F, U+0490-0491, U+04B0-04B1, U+2116",
};

const download = async (path: string): Promise<Uint8Array> => {
  const res = await fetch(`${RAW}/${path}`);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return new Uint8Array(await res.arrayBuffer());
};

const main = async () => {
  await mkdir(FONT_DIR, { recursive: true });
  const work = await mkdtemp(join(tmpdir(), "fixel-"));
  const rules = [
    "/* Generated by scripts/fetch-fonts.ts — do not edit by hand. */",
  ];

  await writeFile(join(FONT_DIR, "Fixel-OFL.txt"), await download("OFL.txt"));

  for (const face of FACES) {
    const source = join(work, `${face.file}.woff2`);
    await writeFile(
      source,
      await download(`fonts/webfonts/${face.file}.woff2`),
    );

    for (const [subset, range] of Object.entries(SUBSETS)) {
      const file = `${face.file.toLowerCase()}-${subset}.woff2`;
      const out = join(FONT_DIR, file);
      const run = Bun.spawnSync([
        "pyftsubset",
        source,
        `--unicodes=${range.replaceAll(" ", "")}`,
        "--flavor=woff2",
        "--layout-features=*",
        `--output-file=${out}`,
      ]);
      if (run.exitCode !== 0) {
        throw new Error(`${file}: ${run.stderr.toString()}`);
      }

      rules.push(
        "@font-face {",
        `  font-family: "${face.family}";`,
        "  font-style: normal;",
        `  font-weight: ${face.weight};`,
        "  font-display: swap;",
        `  src: url("/fonts/${file}") format("woff2");`,
        `  unicode-range: ${range};`,
        "}",
      );
      console.log(`${file}  ${(Bun.file(out).size / 1024).toFixed(1)} KB`);
    }
  }

  await writeFile(CSS_OUT, `${rules.join("\n")}\n`);
};

await main();
